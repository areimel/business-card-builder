// Downloads the Google Fonts families used by themes/fonts/sets/*.css into
// themes/fonts/<id>/ (latin woff2 + font.css + OFL.txt), via the Fontsource API/CDN.
// Run once after adding a family to FAMILIES; the output is committed, so
// render/PDF never touch the network.   Usage: node scripts/fetch-fonts.js [id…]
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FONTS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'themes', 'fonts');
const API = 'https://api.fontsource.org/v1';
const CDN = 'https://cdn.jsdelivr.net/fontsource/fonts';
const OFL = 'https://raw.githubusercontent.com/google/fonts/main/ofl';
const STATIC_WEIGHTS = [400, 500, 600, 700];

/** Fontsource ids. Variable families ship one file per style; static ones use STATIC_WEIGHTS. */
export const FAMILIES = [
  'jetbrains-mono', 'ibm-plex-mono', 'geist-mono', 'martian-mono', 'fira-code', 'space-mono',
  'source-serif-4', 'eb-garamond', 'ibm-plex-serif', 'newsreader', 'crimson-pro',
  'dm-sans', 'dm-mono',
];

async function get(url, as = 'json') {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return as === 'json' ? res.json() : as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
}

const range = (axis) => `${axis.min} ${axis.max}`;

function fontFace(family, file, style, weight, stretch) {
  return `@font-face {
  font-family: "${family}";
  src: url("./${file}") format("woff2");
  font-style: ${style};
  font-weight: ${weight};${stretch ? `\n  font-stretch: ${stretch};` : ''}
  font-display: block;
}
`;
}

async function fetchFamily(id) {
  const meta = await get(`${API}/fonts/${id}`);
  const dir = path.join(FONTS_DIR, id);
  mkdirSync(dir, { recursive: true });
  const faces = [];
  const save = async (url, file) => writeFileSync(path.join(dir, file), await get(url, 'buffer'));

  if (meta.variable) {
    const { axes } = await get(`${API}/variable/${id}`);
    const extra = Object.keys(axes).some((a) => !['wght', 'ital'].includes(a));
    const kind = extra ? 'standard' : 'wght';
    const stretch = axes.wdth && `${range(axes.wdth).replace(' ', '% ')}%`;
    for (const style of meta.styles) {
      const file = `latin-${kind}-${style}.woff2`;
      await save(`${CDN}/${id}:vf@latest/${file}`, file);
      faces.push(fontFace(meta.family, file, style, range(axes.wght), stretch));
    }
  } else {
    for (const style of meta.styles) {
      for (const w of STATIC_WEIGHTS.filter((x) => meta.weights.includes(x))) {
        const file = `latin-${w}-${style}.woff2`;
        await save(meta.variants[w][style].latin.url.woff2, file);
        faces.push(fontFace(meta.family, file, style, w));
      }
    }
  }
  writeFileSync(path.join(dir, 'font.css'), `/* ${meta.family} — generated by scripts/fetch-fonts.js (${meta.license}) */\n${faces.join('')}`);
  writeFileSync(path.join(dir, 'OFL.txt'), await get(`${OFL}/${id.replaceAll('-', '')}/OFL.txt`, 'text'));
  console.log(`✓ ${meta.family} (${faces.length} face${faces.length === 1 ? '' : 's'})`);
}

const ids = process.argv.slice(2);
for (const id of ids.length ? ids : FAMILIES) await fetchFamily(id);
